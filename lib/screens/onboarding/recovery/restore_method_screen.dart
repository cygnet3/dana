import 'package:bitcoin_ui/bitcoin_ui.dart';
import 'package:danawallet/generated/rust/api/bip39.dart';
import 'package:danawallet/generated/rust/api/structs/network.dart';
import 'package:danawallet/screens/onboarding/recovery/descriptor_screen.dart';
import 'package:danawallet/screens/onboarding/recovery/seed_phrase.dart';
import 'package:danawallet/widgets/skeletons/screen_skeleton.dart';
import 'package:flutter/material.dart';

class RestoreMethodScreen extends StatelessWidget {
  final Network network;

  const RestoreMethodScreen({super.key, required this.network});

  @override
  Widget build(BuildContext context) {
    final body = ListView(
      children: [
        ListTile(
          contentPadding: EdgeInsets.zero,
          leading: Icon(Icons.key_outlined, color: Bitcoin.blue),
          title: Text(
            'Recovery phrase',
            style: BitcoinTextStyle.body3(Bitcoin.neutral8),
          ),
          subtitle: Text(
            '12 words generated by Dana',
            style: BitcoinTextStyle.body4(Bitcoin.neutral6),
          ),
          trailing: Icon(Icons.chevron_right, color: Bitcoin.neutral6),
          onTap: () {
            Navigator.push(
              context,
              MaterialPageRoute(
                builder: (context) => SeedPhraseScreen(
                  bip39Words: getEnglishWordlist(),
                  network: network,
                ),
              ),
            );
          },
        ),
        const Divider(),
        ListTile(
          contentPadding: EdgeInsets.zero,
          leading: Icon(Icons.description_outlined, color: Bitcoin.blue),
          title: Text(
            'Descriptor',
            style: BitcoinTextStyle.body3(Bitcoin.neutral8),
          ),
          subtitle: Text(
            'Paste an sp() descriptor',
            style: BitcoinTextStyle.body4(Bitcoin.neutral6),
          ),
          trailing: Icon(Icons.chevron_right, color: Bitcoin.neutral6),
          onTap: () {
            Navigator.push(
              context,
              MaterialPageRoute(
                builder: (context) => DescriptorRestoreScreen(network: network),
              ),
            );
          },
        ),
      ],
    );

    return ScreenSkeleton(
      title: 'Restore wallet',
      showBackButton: true,
      body: body,
    );
  }
}
